#!/usr/bin/env python3
"""bdf2c.py - convert a fixed-width BDF font to a C table of 256 glyphs.

Each glyph is HEIGHT bytes, one per row, leftmost pixel in bit 7.
Usage: bdf2c.py font.bdf name > out.c
"""
import sys


def main():
    path, name = sys.argv[1], sys.argv[2]
    lines = open(path, encoding="latin-1").read().splitlines()
    width = height = ascent = 0
    for ln in lines:
        if ln.startswith("FONTBOUNDINGBOX"):
            _, w, h, _x, y = ln.split()
            width, height, base_y = int(w), int(h), int(y)
        elif ln.startswith("FONT_ASCENT"):
            ascent = int(ln.split()[1])
    glyphs = {}
    i = 0
    while i < len(lines):
        if lines[i].startswith("STARTCHAR"):
            code, bbx, rows = None, None, []
            i += 1
            while not lines[i].startswith("ENDCHAR"):
                ln = lines[i]
                if ln.startswith("ENCODING"):
                    code = int(ln.split()[1])
                elif ln.startswith("BBX"):
                    bbx = [int(v) for v in ln.split()[1:]]
                elif ln == "BITMAP":
                    i += 1
                    while not lines[i].startswith("ENDCHAR"):
                        rows.append(int(lines[i][:2], 16))  # <= 8 px wide: 2 hex digits
                        i += 1
                    break
                i += 1
            if code is not None and 0 <= code < 256 and bbx:
                bw, bh, bx, by = bbx
                cell = [0] * height
                top = ascent - (by + bh)  # row in cell where the bitmap starts
                for r, bits in enumerate(rows):
                    y = top + r
                    if 0 <= y < height:
                        cell[y] = (bits >> bx) & 0xFF
                glyphs[code] = cell
        i += 1

    print(f"/* {width}x{height} glyphs from {path.split('/')[-1]} (public domain), */")
    print("/* one byte per row, leftmost pixel in bit 7. Generated by bdf2c.py. */")
    print(f"const unsigned char {name}[256][{height}] = {{")
    for c in range(256):
        cell = glyphs.get(c, [0] * height)
        print("\t{" + ", ".join(f"0x{b:02x}" for b in cell) + "},")
    print("};")


if __name__ == "__main__":
    main()
