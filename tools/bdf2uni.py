#!/usr/bin/env python3
"""bdf2uni.py - convert a fixed-width Unicode BDF font to C tables.

Emits every glyph in the Basic Multilingual Plane, sorted by code point:
    font_uni_count, font_uni_cp[] (code points), font_uni_bits[][HEIGHT]
Each glyph is HEIGHT bytes, one per row, leftmost pixel in bit 7.
Usage: bdf2uni.py font.bdf > out.c
"""
import sys


def main():
    path = sys.argv[1]
    lines = open(path, encoding="latin-1").read().splitlines()
    height = ascent = 0
    for ln in lines:
        if ln.startswith("FONTBOUNDINGBOX"):
            height = int(ln.split()[2])
        elif ln.startswith("FONT_ASCENT"):
            ascent = int(ln.split()[1])
    glyphs = {}
    i = 0
    while i < len(lines):
        if lines[i].startswith("STARTCHAR"):
            code, bbx, rows = None, None, []
            i += 1
            while not lines[i].startswith("ENDCHAR"):
                ln = lines[i]
                if ln.startswith("ENCODING"):
                    code = int(ln.split()[1])
                elif ln.startswith("BBX"):
                    bbx = [int(v) for v in ln.split()[1:]]
                elif ln == "BITMAP":
                    i += 1
                    while not lines[i].startswith("ENDCHAR"):
                        rows.append(int(lines[i][:2], 16))
                        i += 1
                    break
                i += 1
            if code is not None and 0 <= code < 0x10000 and bbx:
                bw, bh, bx, by = bbx
                cell = [0] * height
                top = ascent - (by + bh)
                for r, bits in enumerate(rows):
                    y = top + r
                    if 0 <= y < height:
                        cell[y] = (bits >> bx) & 0xFC   # 6 pixels wide
                glyphs[code] = cell
        i += 1

    cps = sorted(glyphs)
    print(f"/* {len(cps)} glyphs from {path.split('/')[-1]} (public domain), */")
    print("/* one byte per row, leftmost pixel in bit 7. Generated by bdf2uni.py. */")
    print(f"const int font_uni_count = {len(cps)};")
    print(f"const unsigned short font_uni_cp[{len(cps)}] = {{")
    for k in range(0, len(cps), 10):
        print("\t" + ", ".join(f"0x{c:04x}" for c in cps[k:k + 10]) + ",")
    print("};")
    print(f"const unsigned char font_uni_bits[{len(cps)}][{height}] = {{")
    for c in cps:
        print("\t{" + ",".join(f"0x{b:02x}" for b in glyphs[c]) + "},")
    print("};")


if __name__ == "__main__":
    main()
